"""
Evaluation suite for OLORIC model.
"""
import json
import os
from typing import List, Dict, Any, Optional
from dataclasses import dataclass, field
from pydantic import ValidationError
from .schemas.model_input import OloricModelInput
from .schemas.model_output import OloricModelOutput
from .inference import inference_engine
from .config import config
import logging

logger = logging.getLogger(__name__)


@dataclass
class EvaluationResult:
    """Result of evaluating a single example."""
    example_id: str
    dimension_scores: Dict[str, float]
    overall_score: Optional[float]
    feedback: str
    model_output: Optional[OloricModelOutput]
    expected_output: OloricModelOutput
    # Schema validation metadata
    schema_valid: bool = True
    raw_response: Optional[str] = None
    validation_error: Optional[str] = None
    # Literal text generated by the model before any parsing/validation
    raw_generated_text: Optional[str] = None


class OloricEvaluator:
    """Handles evaluation of OLORIC model."""
    
    def __init__(self, inference_engine: Optional[Any] = None):
        """Initialize OLORIC evaluator."""
        self.eval_config = config.get_evaluation_config()
        self.dimensions = self.eval_config.get("dimensions", {})
        self.benchmark_path = self.eval_config.get("benchmark", {}).get("path", "./evaluation/benchmark.jsonl")
        self.inference_engine = inference_engine
        
    def load_benchmark(self) -> List[Dict[str, Any]]:
        """
        Load evaluation benchmark.
        
        Returns:
            List of evaluation examples
        """
        try:
            with open(self.benchmark_path, 'r', encoding='utf-8') as f:
                examples = []
                for line in f:
                    line = line.strip()
                    if line:
                        try:
                            examples.append(json.loads(line))
                        except json.JSONDecodeError as e:
                            logger.warning(f"Failed to parse benchmark line: {e}")
                return examples
        except FileNotFoundError:
            logger.error(f"Benchmark file not found: {self.benchmark_path}")
            return []
    
    def evaluate_example(self, example: Dict[str, Any]) -> EvaluationResult:
        """
        Evaluate a single example.

        When the model output violates the OloricModelOutput schema (e.g. a
        required field such as ``diagnosis.severity`` is absent), the result is
        recorded with ``schema_valid=False``, ``raw_response`` set to the
        generated text, and ``validation_error`` containing the Pydantic error
        detail.  The example is NOT dropped from the report.

        Args:
            example: Evaluation example dictionary

        Returns:
            EvaluationResult object
        """
        example_id = example.get("id", "unknown")

        # Convert context and target to proper objects
        context = OloricModelInput(**example["context"])
        expected_output = OloricModelOutput(**example["target"])

        # --- Generate model output & catch schema failures ---
        raw_response: Optional[str] = None
        model_output: Optional[OloricModelOutput] = None
        schema_valid = True
        validation_error_msg: Optional[str] = None

        engine = self.inference_engine if self.inference_engine is not None else inference_engine

        try:
            model_output = engine.generate_response(context)
        except ValidationError as ve:
            schema_valid = False
            validation_error_msg = str(ve)
            # Attempt to recover the raw text from the formatter's last output
            # (inference_engine stores it on the exception's raw_response attr
            # if available; otherwise we use the string repr)
            raw_response = getattr(ve, "raw_response", None) or repr(ve)
            logger.warning(
                f"Schema validation failure for example '{example_id}': "
                f"{validation_error_msg}"
            )

        # Capture the literal generated text (set by the inference engine before
        # parsing) so that the exact model output is always auditable.
        raw_generated_text = getattr(engine, "last_raw_text", None)

        if schema_valid:
            # NOTE: Semantic dimension scoring requires human judgment and is
            # intentionally NOT automated here (see
            # evaluation/baseline/semantic_rubric.md). The previous placeholder
            # returned a constant 3.0, which produced deceptive "3.00" aggregate
            # reports. No automated dimension scores are emitted; manual scores
            # must be recorded in evaluation/<run>/scores_semantic.jsonl.
            dimension_scores: Dict[str, float] = {}
            overall_score: Optional[float] = None
            feedback = ("Structural evaluation only. Semantic scoring must be performed "
                        "manually per evaluation/baseline/semantic_rubric.md and "
                        "recorded in scores_semantic.jsonl.")
            if raw_response is None and model_output is not None:
                try:
                    raw_response = model_output.json()
                except Exception:
                    raw_response = str(model_output)
        else:
            # Cannot score without a valid output; no scores are emitted rather
            # than recording zero placeholders.
            dimension_scores = {}
            overall_score = None
            feedback = f"Schema validation failed: {validation_error_msg}"

        return EvaluationResult(
            example_id=example_id,
            dimension_scores=dimension_scores,
            overall_score=overall_score,
            feedback=feedback,
            model_output=model_output,
            expected_output=expected_output,
            schema_valid=schema_valid,
            raw_response=raw_response,
            validation_error=validation_error_msg,
            raw_generated_text=raw_generated_text,
        )
    
    def _score_dimension(self, dimension_name: str, context: OloricModelInput,
                        model_output: OloricModelOutput, 
                        expected_output: OloricModelOutput) -> float:
        """
        Score a specific evaluation dimension.
        
        Args:
            dimension_name: Name of dimension to score
            context: Input context
            model_output: Model's output
            expected_output: Expected output
            
        Returns:
            Score from 0.0 to 4.0
        """
        # Semantic dimensions require human judgment (see
        # evaluation/baseline/semantic_rubric.md) and are intentionally NOT
        # automated. The former placeholder silently returned a constant 3.0,
        # which produced deceptive aggregate scores in evaluation reports.
        # Any genuine automated scorer must be implemented here explicitly;
        # this method will never fabricate a score.
        raise NotImplementedError(
            "Automated semantic scoring is not implemented. Score manually with "
            "evaluation/baseline/semantic_rubric.md and record the results in "
            "scores_semantic.jsonl. (The previous placeholder returned a fixed "
            "3.0, producing invalid '3.00' reports.)"
        )
    
    def _calculate_overall_score(self, dimension_scores: Dict[str, float]) -> float:
        """
        Calculate overall score from dimension scores.
        
        Args:
            dimension_scores: Dictionary of dimension scores
            
        Returns:
            Overall score
        """
        if not dimension_scores:
            return 0.0
        
        # Get weights from config
        weights = {}
        total_weight = 0.0
        for name in dimension_scores.keys():
            weight = config.get(f"evaluation.dimensions.{name}.weight", 0.0)
            weights[name] = weight
            total_weight += weight
        
        # Normalize weights if they don't sum to 1
        if total_weight > 0:
            weights = {name: weight/total_weight for name, weight in weights.items()}
        else:
            # Equal weighting if no weights specified
            weights = {name: 1.0/len(dimension_scores) for name in dimension_scores.keys()}
        
        # Calculate weighted average
        overall_score = sum(
            score * weights[name] for name, score in dimension_scores.items()
        )
        
        return round(overall_score, 2)
    
    def _generate_feedback(self, dimension_scores: Dict[str, float],
                          model_output: OloricModelOutput,
                          expected_output: OloricModelOutput) -> str:
        """
        Generate feedback for the evaluation.
        
        Args:
            dimension_scores: Dictionary of dimension scores
            model_output: Model's output
            expected_output: Expected output
            
        Returns:
            Feedback string
        """
        # Find lowest scoring dimensions
        sorted_dims = sorted(dimension_scores.items(), key=lambda x: x[1])
        lowest_dims = sorted_dims[:2] if len(sorted_dims) >= 2 else sorted_dims
        
        feedback_parts = []
        if lowest_dims:
            feedback_parts.append(f"Areas for improvement: {', '.join([dim for dim, score in lowest_dims])}")
        
        # Check if response is too short/long
        response_length = len(model_output.response.split())
        if response_length < 10:
            feedback_parts.append("Response may be too brief")
        elif response_length > 200:
            feedback_parts.append("Response may be overly verbose")
        
        # Check if understanding check is appropriate
        if model_output.understanding_check.required and not model_output.understanding_check.question:
            feedback_parts.append("Understanding check required but no question provided")
        
        if not feedback_parts:
            feedback_parts.append("Performance is satisfactory across dimensions")
        
        return "; ".join(feedback_parts)
    
    def evaluate_benchmark(self, limit: Optional[int] = None,
                           on_result: Optional[Any] = None) -> List[EvaluationResult]:
        """
        Evaluate the entire benchmark.

        Every example is evaluated.  Schema validation failures are recorded
        in the returned EvaluationResult (``schema_valid=False``) rather than
        silently dropped.  Only genuine infrastructure errors (e.g. OOM, broken
        context JSON) cause an example to be skipped, and those are logged at
        ERROR level with a clear reason.

        Args:
            limit: Maximum number of examples to evaluate (None for all)

        Returns:
            List of EvaluationResult objects
        """
        examples = self.load_benchmark()
        if limit:
            examples = examples[:limit]

        results = []
        for example in examples:
            example_id = example.get("id", "unknown")
            try:
                result = self.evaluate_example(example)
                results.append(result)
                if on_result is not None:
                    try:
                        on_result(result)
                    except Exception:
                        logger.exception("on_result callback failed")
                status = "PASS" if result.schema_valid else "SCHEMA_FAIL"
                score_str = (f"{result.overall_score:.3f}"
                             if result.overall_score is not None else "N/A (manual)")
                logger.info(
                    f"[{status}] example='{result.example_id}' "
                    f"score={score_str}"
                )
            except Exception as e:
                # Only infrastructure errors (not schema failures) land here
                # because schema failures are caught inside evaluate_example.
                logger.error(
                    f"[INFRA_ERROR] example='{example_id}' skipped: "
                    f"{type(e).__name__}: {e}"
                )
        return results

    def generate_report(self, results: List[EvaluationResult]) -> Dict[str, Any]:
        """
        Generate a report from evaluation results.

        The report includes:
        - Overall and per-dimension score statistics (schema-valid results only
          for the "valid" stats; all results for counts).
        - A dedicated ``schema_failures`` section listing every example that
          failed schema validation, with the raw response and error detail.

        Args:
            results: List of EvaluationResult objects

        Returns:
            Dictionary containing the report
        """
        if not results:
            return {
                "num_examples": 0,
                "num_schema_valid": 0,
                "num_schema_failures": 0,
                "schema_failure_rate": 0.0,
                "semantic_scoring": "manual_only",
                "overall_score": None,
                "dimension_scores": {},
                "schema_failures": [],
            }

        valid_results   = [r for r in results if r.schema_valid]
        invalid_results = [r for r in results if not r.schema_valid]

        # --- Score statistics ---
        # Only results that actually carry automated dimension scores are
        # aggregated. The automated harness performs structural checks only;
        # semantic scoring is manual (see evaluation/baseline/semantic_rubric.md),
        # so when no dimension scores exist the report contains None/{} rather
        # than fabricated numbers.
        scored_results = [r for r in valid_results if r.dimension_scores]
        has_automated_scores = bool(scored_results)

        overall_block: Optional[Dict[str, Any]] = None
        dimension_scores: Dict[str, Any] = {}
        if has_automated_scores:
            overall_scores = [r.overall_score for r in scored_results if r.overall_score is not None]
            if overall_scores:
                overall_block = {
                    "mean": round(sum(overall_scores) / len(overall_scores), 4),
                    "min":  round(min(overall_scores), 4),
                    "max":  round(max(overall_scores), 4),
                }
            for dim_name in scored_results[0].dimension_scores.keys():
                dim_values = [r.dimension_scores.get(dim_name, 0.0) for r in scored_results]
                dimension_scores[dim_name] = {
                    "mean": sum(dim_values) / len(dim_values),
                    "min":  min(dim_values),
                    "max":  max(dim_values),
                }

        # --- Schema failure details ---
        schema_failures = [
            {
                "example_id":       r.example_id,
                "raw_response":     r.raw_response,
                "raw_generated_text": r.raw_generated_text,
                "validation_error": r.validation_error,
            }
            for r in invalid_results
        ]

        num_total    = len(results)
        num_failures = len(invalid_results)

        report = {
            "num_examples":        num_total,
            "num_schema_valid":    num_total - num_failures,
            "num_schema_failures": num_failures,
            "schema_failure_rate": round(num_failures / num_total, 4),
            "semantic_scoring":    "automated" if has_automated_scores else "manual_only",
            "overall_score":       overall_block,
            "dimension_scores":    dimension_scores,
            "schema_failures":     schema_failures,
        }

        return report
